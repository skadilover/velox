// Read the append-only table and verify numeric precision (price as REAL,
// score as DOUBLE).
TEST_F(PaimonE2ETest, appendOnlyNumericPrecision) {
  auto files =
      listOrcFiles(kWarehouse + "/append_table/bucket-0");
  ASSERT_EQ(files.size(), 1);

  auto outputType =
      ROW({"id", "price", "score"}, {INTEGER(), REAL(), DOUBLE()});

  auto dataColumns = ROW(
      {"id", "name", "amount", "price", "score", "active", "event_date",
       "total", "event_time"},
      {INTEGER(),
       VARCHAR(),
       BIGINT(),
       REAL(),
       DOUBLE(),
       BOOLEAN(),
       DATE(),
       DECIMAL(10, 2),
       TIMESTAMP()});

  PaimonConnectorSplitBuilder builder(
      kPaimonConnectorId,
      /*snapshotId=*/1,
      PaimonTableType::kAppendOnly,
      dwio::common::FileFormat::ORC);
  builder.addFile(files[0], /*fileSize=*/0);
  builder.rawConvertible(true);
  auto split = builder.build();

  auto plan = makePaimonScanPlan(outputType, dataColumns);
  auto result = execute(plan, {split});

  ASSERT_EQ(result->size(), 5);

  auto ids = result->childAt(0)->asFlatVector<int32_t>();
  auto prices = result->childAt(1)->asFlatVector<float>();
  auto scores = result->childAt(2)->asFlatVector<double>();

  std::unordered_map<int32_t, vector_size_t> idToRow;
  for (vector_size_t i = 0; i < result->size(); ++i) {
    idToRow[ids->valueAt(i)] = i;
  }

  // Alice: price=9.99, score=95.5
  ASSERT_TRUE(idToRow.count(1));
  EXPECT_NEAR(prices->valueAt(idToRow[1]), 9.99f, 0.01f);
  EXPECT_NEAR(scores->valueAt(idToRow[1]), 95.5, 0.001);

  // Bob: price=19.99, score=88.0
  ASSERT_TRUE(idToRow.count(2));
  EXPECT_NEAR(prices->valueAt(idToRow[2]), 19.99f, 0.01f);
  EXPECT_NEAR(scores->valueAt(idToRow[2]), 88.0, 0.001);
}

// PK table: read with rawConvertible=false (merge-on-read).
// Two ORC files with overlapping keys should produce 5 deduplicated rows.
TEST_F(PaimonE2ETest, pkTableMergeOnRead) {
  auto files = listOrcFiles(kWarehouse + "/pk_table/bucket-0");
  ASSERT_EQ(files.size(), 2) << "Expected 2 ORC files for pk_table";

  // User-facing output columns (no system columns).
  auto outputType = ROW(
      {"user_id", "name", "score", "level"},
      {BIGINT(), VARCHAR(), DOUBLE(), INTEGER()});

  PaimonConnectorSplitBuilder builder(
      kPaimonConnectorId,
      /*snapshotId=*/2,
      PaimonTableType::kPrimaryKey,
      dwio::common::FileFormat::ORC);

  // Add files with distinct levels so merge-on-read sees them correctly.
  // File 0 (snapshot-1 data, older) at level 1.
  // File 1 (snapshot-2 data, newer) at level 0.
  // Sorted by name: data-02... is file1(snapshot-2), data-04... is
  // file0(snapshot-1). We use sequence numbers to determine order.
  for (size_t i = 0; i < files.size(); ++i) {
    // Level assignment: first file (alphabetically) at level 0,
    // second at level 1. Sequence numbers determine winner.
    builder.addFile(files[i], /*fileSize=*/0, /*level=*/static_cast<int32_t>(i));
  }
  builder.rawConvertible(false);
  builder.primaryKeys({"user_id"});
  builder.mergeEngine("deduplicate");
  builder.tableBucketNumber(0);
  auto split = builder.build();

  auto plan = makePaimonScanPlan(outputType);
  auto result = execute(plan, {split});

  // After merge, should have 5 unique user_ids.
  ASSERT_EQ(result->size(), 5)
      << "pk_table should have 5 rows after merge-on-read";

  auto userIds = result->childAt(0)->asFlatVector<int64_t>();
  auto names = result->childAt(1)->asFlatVector<StringView>();
  auto scores = result->childAt(2)->asFlatVector<double>();
  auto levels = result->childAt(3)->asFlatVector<int32_t>();

  std::unordered_map<int64_t, vector_size_t> idToRow;
  for (vector_size_t i = 0; i < result->size(); ++i) {
    idToRow[userIds->valueAt(i)] = i;
  }

  // Verify all 5 user_ids are present.
  EXPECT_TRUE(idToRow.count(1));
  EXPECT_TRUE(idToRow.count(2));
  EXPECT_TRUE(idToRow.count(3));
  EXPECT_TRUE(idToRow.count(4));
  EXPECT_TRUE(idToRow.count(5));

  // user_id=1: updated in commit 2 -> score=97.0, level=11
  EXPECT_EQ(names->valueAt(idToRow[1]).getString(), "Alice");
  EXPECT_NEAR(scores->valueAt(idToRow[1]), 97.0, 0.001);
  EXPECT_EQ(levels->valueAt(idToRow[1]), 11);

  // user_id=2: not updated -> score=88.0, level=8
  EXPECT_EQ(names->valueAt(idToRow[2]).getString(), "Bob");
  EXPECT_NEAR(scores->valueAt(idToRow[2]), 88.0, 0.001);
  EXPECT_EQ(levels->valueAt(idToRow[2]), 8);

  // user_id=3: updated in commit 2 -> score=78.5, level=6
  EXPECT_EQ(names->valueAt(idToRow[3]).getString(), "Charlie");
  EXPECT_NEAR(scores->valueAt(idToRow[3]), 78.5, 0.001);
  EXPECT_EQ(levels->valueAt(idToRow[3]), 6);

  // user_id=4: not updated -> score=91.7, level=9
  EXPECT_EQ(names->valueAt(idToRow[4]).getString(), "Diana");
  EXPECT_NEAR(scores->valueAt(idToRow[4]), 91.7, 0.001);
  EXPECT_EQ(levels->valueAt(idToRow[4]), 9);

  // user_id=5: new in commit 2 -> score=85.0, level=7
  EXPECT_EQ(names->valueAt(idToRow[5]).getString(), "Eve");
  EXPECT_NEAR(scores->valueAt(idToRow[5]), 85.0, 0.001);
  EXPECT_EQ(levels->valueAt(idToRow[5]), 7);
}

// PK table: read with column projection on merge path.
TEST_F(PaimonE2ETest, pkTableMergeColumnProjection) {
  auto files = listOrcFiles(kWarehouse + "/pk_table/bucket-0");
  ASSERT_EQ(files.size(), 2);

  // Only project user_id and score.
  auto outputType = ROW({"user_id", "score"}, {BIGINT(), DOUBLE()});

  PaimonConnectorSplitBuilder builder(
      kPaimonConnectorId,
      /*snapshotId=*/2,
      PaimonTableType::kPrimaryKey,
      dwio::common::FileFormat::ORC);

  for (size_t i = 0; i < files.size(); ++i) {
    builder.addFile(files[i], /*fileSize=*/0, /*level=*/static_cast<int32_t>(i));
  }
  builder.rawConvertible(false);
  builder.primaryKeys({"user_id"});
  builder.mergeEngine("deduplicate");
  builder.tableBucketNumber(0);
  auto split = builder.build();

  auto plan = makePaimonScanPlan(outputType);
  auto result = execute(plan, {split});

  ASSERT_EQ(result->size(), 5);
  ASSERT_EQ(result->type()->size(), 2);

  auto userIds = result->childAt(0)->asFlatVector<int64_t>();
  auto scores = result->childAt(1)->asFlatVector<double>();

  std::unordered_map<int64_t, double> idToScore;
  for (vector_size_t i = 0; i < result->size(); ++i) {
    idToScore[userIds->valueAt(i)] = scores->valueAt(i);
  }

  EXPECT_NEAR(idToScore[1], 97.0, 0.001);
  EXPECT_NEAR(idToScore[2], 88.0, 0.001);
  EXPECT_NEAR(idToScore[3], 78.5, 0.001);
  EXPECT_NEAR(idToScore[4], 91.7, 0.001);
  EXPECT_NEAR(idToScore[5], 85.0, 0.001);
}

