/// End-to-end tests that read real Paimon ORC files generated by the Java
/// Paimon API. These tests validate the Velox Paimon connector against actual
/// Paimon table data at /data/test/paimon/db1.
///
/// Test data layout:
///   append_table: 1 snapshot, 1 ORC file, 5 rows
///     Schema: id(INT), name(STRING), amount(BIGINT), price(FLOAT),
///             score(DOUBLE), active(BOOLEAN), event_date(DATE),
///             total(DECIMAL(10,2)), event_time(TIMESTAMP(3))
///
///   pk_table: 2 snapshots (deduplicate merge engine), 2 ORC files, 7 raw rows
///     Schema (user columns): user_id(BIGINT), name(STRING), score(DOUBLE),
///                            level(INT), updated_at(TIMESTAMP(3))
///     ORC KV schema: _KEY_user_id, _SEQUENCE_NUMBER, _VALUE_KIND,
///                    user_id, name, score, level, updated_at
///     After merge: 5 unique rows (user_id 1,3 updated; user_id 5 new)

